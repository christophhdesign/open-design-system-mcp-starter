test('skill: writes use-<id> and review-<id> SKILL.md with front matter whose name matches its directory', () => {
  const data = makeSystemData();
  const out = tempDir();
  const result = runGenerate(data, { target: 'skill', outDir: out });

  const usePath = resolve(out, '.claude/skills/use-acme/SKILL.md');
  const reviewPath = resolve(out, '.claude/skills/review-acme/SKILL.md');
  assert.ok(result.written.includes(usePath));
  assert.ok(result.written.includes(reviewPath));

  const useFront = parseFrontMatter(readFileSync(usePath, 'utf8'));
  assert.equal(useFront.name, 'use-acme');
  assert.ok(useFront.description && useFront.description.length > 0);

  const reviewFront = parseFrontMatter(readFileSync(reviewPath, 'utf8'));
  assert.equal(reviewFront.name, 'review-acme');

  const useBody = readFileSync(usePath, 'utf8');
  assert.match(useBody, /search_components/);
  assert.match(useBody, /find_token/);

  const reviewBody = readFileSync(reviewPath, 'utf8');
  assert.match(reviewBody, /check_usage/);
});

