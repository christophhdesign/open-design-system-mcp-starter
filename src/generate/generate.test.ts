test('well-known: servers.json is valid JSON and carries the server command', () => {
  const data = makeSystemData();
  const out = tempDir();
  const result = runGenerate(data, { target: 'well-known', outDir: out, serverCommand: 'npx tsx /abs/src/cli.ts serve --config /abs/ds.config.json' });

  const path = resolve(out, '.well-known/mcp/servers.json');
  assert.ok(result.written.includes(path));

  const json = JSON.parse(readFileSync(path, 'utf8')) as { servers: Array<{ name: string; transport: { type: string; command: string; args: string[] } }> };
  assert.equal(json.servers.length, 1);
  const server = json.servers[0]!;
  assert.equal(server.name, 'acme');
  assert.equal(server.transport.type, 'stdio');
  assert.equal(server.transport.command, 'npx');
  assert.deepEqual(server.transport.args, ['tsx', '/abs/src/cli.ts', 'serve', '--config', '/abs/ds.config.json']);
  assert.ok(result.notes.some((n) => n.includes('P3')));
});

