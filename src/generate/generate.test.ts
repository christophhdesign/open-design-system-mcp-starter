import assert from 'node:assert/strict';
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { test } from 'node:test';

import { makeSystemData } from '../test-helpers.ts';
import { runGenerate } from './index.ts';

function tempDir(): string {
  return mkdtempSync(join(tmpdir(), 'ds-mcp-generate-'));
}

function parseFrontMatter(content: string): Record<string, string> {
  const match = /^---\n([\s\S]*?)\n---/.exec(content);
  assert.ok(match, 'expected a leading --- front-matter block');
  const fields: Record<string, string> = {};
  for (const line of match![1]!.split('\n')) {
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    if (value.startsWith('"') && value.endsWith('"')) {
      value = JSON.parse(value);
    }
    fields[key] = value;
  }
  return fields;
}

test('agents-md: creates AGENTS.md with a fenced section, never touches a missing CLAUDE.md', () => {
  const data = makeSystemData();
  const out = tempDir();
  const result = runGenerate(data, { target: 'agents-md', outDir: out });

  const agentsPath = resolve(out, 'AGENTS.md');
  assert.ok(result.written.includes(agentsPath));
  assert.equal(existsSync(resolve(out, 'CLAUDE.md')), false);

  const content = readFileSync(agentsPath, 'utf8');
  assert.match(content, /<!-- ds-mcp:begin acme -->/);
  assert.match(content, /<!-- ds-mcp:end acme -->/);
  assert.match(content, /search_components/);
  assert.match(content, /resolve_component/);
  assert.match(content, /find_token/);
});

test('agents-md: updates CLAUDE.md only when it already exists, preserving surrounding text', () => {
  const data = makeSystemData();
  const out = tempDir();
  const claudePath = resolve(out, 'CLAUDE.md');
  writeFileSync(claudePath, '# Team notes\n\nHand-written content stays here.\n', 'utf8');

  runGenerate(data, { target: 'agents-md', outDir: out });

  const content = readFileSync(claudePath, 'utf8');
  assert.match(content, /Hand-written content stays here\./);
  assert.match(content, /<!-- ds-mcp:begin acme -->/);
  assert.match(content, /<!-- ds-mcp:end acme -->/);
});

test('agents-md: a second run with changed data replaces the section instead of duplicating it', () => {
  const out = tempDir();
  const data1 = makeSystemData();
  runGenerate(data1, { target: 'agents-md', outDir: out });

  const data2 = makeSystemData({ cfg: { ...data1.cfg, name: 'Acme Elements Renamed' } });
  runGenerate(data2, { target: 'agents-md', outDir: out });

  const content = readFileSync(resolve(out, 'AGENTS.md'), 'utf8');
  const beginCount = content.split('<!-- ds-mcp:begin acme -->').length - 1;
  const endCount = content.split('<!-- ds-mcp:end acme -->').length - 1;
  assert.equal(beginCount, 1);
  assert.equal(endCount, 1);
  assert.match(content, /Acme Elements Renamed/);
});

test('llms-txt: writes both files and reports their sizes', () => {
  const data = makeSystemData();
  const out = tempDir();
  const result = runGenerate(data, { target: 'llms-txt', outDir: out });

  const shortPath = resolve(out, 'llms.txt');
  const fullPath = resolve(out, 'llms-full.txt');
  assert.ok(result.written.includes(shortPath));
  assert.ok(result.written.includes(fullPath));

  const shortText = readFileSync(shortPath, 'utf8');
  assert.match(shortText, /Surface/); // a real component name from makeSystemData
  assert.match(shortText, /ds:\/\/acme\/components\/Surface/);

  const fullText = readFileSync(fullPath, 'utf8');
  assert.match(fullText, /## Tokens/);
  assert.match(fullText, /Props:/);

  const sizeNote = result.notes.find((n) => n.includes('llms.txt') && n.includes('KB'));
  assert.ok(sizeNote, `expected a size note, got: ${result.notes.join(' | ')}`);
  assert.match(sizeNote!, /llms\.txt \d+(\.\d+)? KB, llms-full\.txt \d+(\.\d+)? KB/);
});

test('llms-txt: force overwrites a pre-existing file; without force it is left alone and reported as skipped', () => {
  const data = makeSystemData();
  const out = tempDir();
  const llmsPath = resolve(out, 'llms.txt');
  writeFileSync(llmsPath, 'hand-written, not generated by this tool\n', 'utf8');

  const withoutForce = runGenerate(data, { target: 'llms-txt', outDir: out });
  assert.ok(withoutForce.skipped.includes(llmsPath));
  assert.ok(!withoutForce.written.includes(llmsPath));
  assert.equal(readFileSync(llmsPath, 'utf8'), 'hand-written, not generated by this tool\n');

  const withForce = runGenerate(data, { target: 'llms-txt', outDir: out, force: true });
  assert.ok(withForce.written.includes(llmsPath));
  assert.notEqual(readFileSync(llmsPath, 'utf8'), 'hand-written, not generated by this tool\n');
});

